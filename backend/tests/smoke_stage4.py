async def _interrupt_payload(graph, config):
    """Extract interrupt payload from graph state (LangGraph 0.2.60+)."""
    snapshot = await graph.aget_state(config)
    if snapshot and hasattr(snapshot, "tasks") and snapshot.tasks:
        for task in snapshot.tasks:
            if hasattr(task, "interrupts") and task.interrupts:
                first = task.interrupts[0]
                return getattr(first, "value", None) or (first if isinstance(first, dict) else None)
    return None


async def main() -> int:
    print("=" * 70)
    print("STAGE 4 SMOKE TEST — real Scorer + GapAnalyzer")
    print("=" * 70)

    graph = await get_compiled_graph_async()
    print("\n[1] Graph compiled ✓")

    session_id = "smoke-stage4-001"
    config = {"configurable": {"thread_id": session_id}}

    # --- Run through all 4 skills, 1 turn each ---
    print("\n[2] Running through interview (1 turn × 4 skills)...")
    result = await graph.ainvoke({
        "resume_text": "(mock)",
        "jd_text": "(mock)",
        "session_id": session_id,
        "messages": [],
    }, config)

    turn = 0
    answers = {
        "Python": "I built a FastAPI service with async/await for handling 10k concurrent users using uvicorn workers.",
        "Kubernetes": "I have heard of pods.",
        "LangGraph": "I used StateGraph with TypedDict and added conditional edges from a supervisor node.",
        "RAG": "I built a chunking pipeline with semantic splitter and Chroma for retrieval.",
    }
    while True:
        payload = await _interrupt_payload(graph, config)
        if payload is None:
            break
        turn += 1
        skill = payload["skill"]
        ans = answers.get(skill, "I'm not sure.")
        print(f"    Turn {turn}: {skill} (bloom={payload['bloom_level']}) — answering...")
        result = await graph.ainvoke(Command(resume=ans), config)
        if turn > 8:
            raise AssertionError("Loop didn't terminate")

    print(f"    ✓ {turn} turns completed")

    # --- Validate Scorer output ---
    print("\n[3] Validating Scorer output:")
    snapshot = await graph.aget_state(config)
    final = snapshot.values
    assessments: list[SkillAssessment] = final.get("skill_assessments", [])
    assert len(assessments) == 4, f"Expected 4 assessments, got {len(assessments)}"

    by_skill = {a.skill: a for a in assessments}

    py = by_skill["Python"]
    print(f"    ✓ Python:     level={py.level.name:10s} confidence={py.confidence:.2f} "
          f"gap_to_required={py.gap_to_required}")
    assert py.level.value >= ProficiencyLevel.APPLY.value, f"Python level should be ≥APPLY, got {py.level.name}"
    assert len(py.evidence) >= 1, "Evidence list must be non-empty"

    k8s = by_skill["Kubernetes"]
    print(f"    ✓ Kubernetes: level={k8s.level.name:10s} confidence={k8s.confidence:.2f} "
          f"gap_to_required={k8s.gap_to_required}")
    assert k8s.level.value <= ProficiencyLevel.UNDERSTAND.value, "Kubernetes should score low"
    assert k8s.gap_to_required is not None and k8s.gap_to_required > 0, "K8s gap should be positive"

    lg = by_skill["LangGraph"]
    print(f"    ✓ LangGraph:  level={lg.level.name:10s} confidence={lg.confidence:.2f} "
          f"gap_to_required={lg.gap_to_required}")

    rag = by_skill["RAG"]
    print(f"    ✓ RAG:        level={rag.level.name:10s} confidence={rag.confidence:.2f} "
          f"gap_to_required={rag.gap_to_required}")

    # --- Validate GapAnalyzer output ---
    print("\n[4] Validating GapAnalyzer output:")
    gap_analysis = final.get("gap_analysis")
    assert gap_analysis is not None, "GapAnalyzer didn't run"

    print(f"    ✓ overall_match: {gap_analysis.overall_match_score:.2f}")
    print(f"    ✓ strengths:     {gap_analysis.strengths}")
    print(f"    ✓ {len(gap_analysis.gaps)} gap(s) identified:")
    for g in gap_analysis.gaps:
        cur = g.current_level.name if g.current_level else "NONE"
        adj = ", ".join(g.adjacent_known_skills) if g.adjacent_known_skills else "(no adjacency available)"
        print(f"        - {g.skill}: current={cur}, required={g.required_level.name}, "
              f"severity={g.severity:.2f}, adjacent=[{adj}]")

    # Strength check: Python should be in strengths (level ≥ ANALYZE for senior, but our mock
    # caps at ANALYZE only when theta >= 1.0; for a single-question loop with score=0.95,
    # theta hits ~1.5, so this should hold.)
    if py.level.value >= 4:  # ANALYZE = 4 = required for senior
        assert "Python" in gap_analysis.strengths, "Python should be a strength for senior role"
        print("    ✓ Python correctly identified as a strength")
    else:
        print(f"    ⚠ Python at level {py.level.name} — single-question IRT undershot; expected at scale")

    # Kubernetes should be the most severe gap (required + zero proficiency)
    top_gap = gap_analysis.gaps[0]
    assert top_gap.skill == "Kubernetes", f"Top gap should be Kubernetes, got {top_gap.skill}"
    print("    ✓ Kubernetes is correctly the highest-severity gap")

    # RAG is preferred (not required) → severity should be lower
    rag_gap = next((g for g in gap_analysis.gaps if g.skill == "RAG"), None)
    if rag_gap:
        assert rag_gap.severity < top_gap.severity, "Preferred-skill gap should be less severe than required-skill gap"
        print(f"    ✓ RAG (preferred) severity {rag_gap.severity:.2f} < Kubernetes (required) {top_gap.severity:.2f}")

    # Summary should be the LLM-generated string
    assert "Kubernetes" in gap_analysis.summary or "kubernetes" in gap_analysis.summary.lower()
    print(f"    ✓ Summary: {gap_analysis.summary[:100]}...")

    print("\n" + "=" * 70)
    print("✅ STAGE 4 SMOKE TEST PASSED")
    print("=" * 70)

    await shutdown_graph()
    os.unlink(tmp_db.name)
    return 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))