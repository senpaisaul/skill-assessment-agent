async def fake_scorer_completion(*, node, response_model, messages, max_tokens=2048, temperature=0.2):
    """Returns a _SkillRubric or _GapSummary depending on the response_model."""
    # Inspect the user prompt to figure out which skill we're scoring
    user_msg = next((m["content"] for m in messages if m["role"] == "user"), "")

    if response_model.__name__ == "_SkillRubric":
        # Find the skill name (we put it on the first line)
        skill = "Unknown"
        for line in user_msg.splitlines():
            if line.startswith("SKILL TO ASSESS:"):
                skill = line.split(":", 1)[1].strip()
                break
        # Map theta to level: parse theta from the prompt
        theta = 0.0
        for line in user_msg.splitlines():
            if "Converged ability estimate" in line:
                try:
                    theta = float(line.split(":")[1].strip().split()[0])
                except Exception:
                    pass
                break

        # Higher theta → higher proposed level
        if theta >= 1.0:
            level = ProficiencyLevel.ANALYZE
            quality = "HIGH"
        elif theta >= 0.0:
            level = ProficiencyLevel.APPLY
            quality = "MEDIUM"
        elif theta >= -1.0:
            level = ProficiencyLevel.UNDERSTAND
            quality = "MEDIUM"
        else:
            level = ProficiencyLevel.REMEMBER
            quality = "LOW"

        return scorer_mod._SkillRubric(
            skill=skill,
            proposed_level=level,
            evidence_quality=quality,
            resume_evidence=[f"Mock resume quote for {skill}"],
            interview_evidence=[f"Mock interview quote for {skill}"],
            reasoning=f"Mock reasoning for {skill}: theta={theta:+.2f} → level {level.name}.",
        )

    if response_model.__name__ == "_GapSummary":
        from app.graph.nodes.gap_analyzer import _GapSummary
        return _GapSummary(
            summary=(
                "Strong fundamentals in Python with real production experience, "
                "but the Kubernetes gap is the critical blocker for a senior role. "
                "LangGraph and RAG are within reach given existing LangChain knowledge."
            )
        )

    raise RuntimeError(f"Unmocked response_model: {response_model.__name__}")


